// =============================================================================
// tb_lk_gradient.v -- self-checking testbench for lk_gradient
//
// What it does:
//   1. Reads two frames and the golden answers computed by Python from vectors/
//   2. Feeds both frames to the DUT in raster order, inserting random bubbles to mimic upstream gaps
//   3. Feeds 2 frames back to back (tests that the next frame starts correctly after one ends)
//   4. Compares every output bit by bit with the golden answer, checks the output order, prints PASS / FAIL
//   5. Writes lk_gradient.vcd, viewable in GTKWave
//
// Optional:  vvp sim +BUBBLE=30   (30% chance per cycle of sending nothing, default 30; 0 = full speed)
// =============================================================================
`timescale 1ns/1ps

module tb_lk_gradient;

    `include "params.vh"            // IMG_W, IMG_H (generated by lk_golden.py)
    localparam NPIX    = IMG_W * IMG_H;
    localparam NFRAMES = 2;

    // ---------------- clock and reset ----------------
    wire [15:0] cfg_w = IMG_W;      // run-time size
    wire [15:0] cfg_h = IMG_H;
    reg clk = 1'b0;
    always #5 clk = ~clk;           // 10 ns period = 100 MHz
    reg rst = 1'b1;

    // ---------------- DUT interface ----------------
    reg         in_valid = 1'b0;
    wire        in_ready;
    reg  [7:0]  in_p0 = 8'd0, in_p1 = 8'd0;
    wire        out_valid, frame_done;
    wire [15:0] out_x, out_y;
    wire signed [8:0] out_ix, out_iy, out_it;

    lk_gradient #(.WMAX(WMAX), .CW(16)) dut (
        .clk(clk), .rst(rst), .cfg_w(cfg_w), .cfg_h(cfg_h),
        .in_valid(in_valid), .in_ready(in_ready), .in_p0(in_p0), .in_p1(in_p1),
        .out_valid(out_valid), .out_x(out_x), .out_y(out_y),
        .out_ix(out_ix), .out_iy(out_iy), .out_it(out_it),
        .frame_done(frame_done)
    );

    // ---------------- test data ----------------
    reg [7:0] f0   [0:NPIX-1];
    reg [7:0] f1   [0:NPIX-1];
    reg [8:0] g_ix [0:NPIX-1];
    reg [8:0] g_iy [0:NPIX-1];
    reg [8:0] g_it [0:NPIX-1];

    integer i, frame, seed, bubble_pct;
    integer n_out = 0, n_err = 0, n_done = 0, cycles = 0;
    integer idx, exp_idx;

    always @(posedge clk) cycles = cycles + 1;

    // ---------------- stimulus: feed pixels ----------------
    initial begin
        $readmemh("vectors/frame0.hex",    f0);
        $readmemh("vectors/frame1.hex",    f1);
        $readmemh("vectors/golden_ix.hex", g_ix);
        $readmemh("vectors/golden_iy.hex", g_iy);
        $readmemh("vectors/golden_it.hex", g_it);
        if (!$value$plusargs("BUBBLE=%d", bubble_pct)) bubble_pct = 30;
        seed = 12345;

        $dumpfile("lk_gradient.vcd");
        $dumpvars(0, tb_lk_gradient);

        repeat (3) @(posedge clk);
        rst <= 1'b0;

        for (frame = 0; frame < NFRAMES; frame = frame + 1) begin
            i = 0;
            while (i < NPIX) begin
                // randomly decide whether to send data this cycle (mimics occasional DMA gaps)
                in_valid <= ((($random(seed) % 100) + 100) % 100) >= bubble_pct;
                in_p0    <= f0[i];
                in_p1    <= f1[i];
                @(posedge clk);
                if (in_valid && in_ready) i = i + 1;   // handshake succeeded this cycle, next pixel
            end
        end
        in_valid <= 1'b0;
    end

    // ---------------- checking: compare outputs one by one ----------------
    always @(posedge clk) begin
        if (out_valid) begin
            idx     = out_y * IMG_W + out_x;
            exp_idx = n_out % NPIX;                    // outputs must be in strict raster order
            if (idx !== exp_idx) begin
                n_err = n_err + 1;
                if (n_err <= 10)
                    $display("ORDER ERROR: output #%0d is (y=%0d,x=%0d), expected index %0d",
                             n_out, out_y, out_x, exp_idx);
            end else if (out_ix !== g_ix[idx] || out_iy !== g_iy[idx] || out_it !== g_it[idx]) begin
                n_err = n_err + 1;
                if (n_err <= 10)
                    $display("MISMATCH (y=%0d,x=%0d): got Ix=%0d Iy=%0d It=%0d | expected Ix=%0d Iy=%0d It=%0d",
                             out_y, out_x, out_ix, out_iy, out_it,
                             $signed(g_ix[idx]), $signed(g_iy[idx]), $signed(g_it[idx]));
            end
            n_out = n_out + 1;
        end
        if (frame_done) n_done = n_done + 1;
    end

    // ---------------- end of test ----------------
    initial begin : finish_block
        wait (n_done == NFRAMES);
        repeat (2) @(posedge clk);
        $display("------------------------------------------------------------");
        $display("Image %0dx%0d, %0d frames, bubble=%0d%%, %0d cycles",
                 IMG_W, IMG_H, NFRAMES, bubble_pct, cycles);
        $display("Outputs: %0d (expected %0d), errors: %0d", n_out, NPIX*NFRAMES, n_err);
        if (n_err == 0 && n_out == NPIX*NFRAMES)
            $display("*** PASS ***");
        else
            $display("*** FAIL ***");
        $display("------------------------------------------------------------");
        $finish;
    end

    // ---------------- watchdog: prevents hangs ----------------
    initial begin
        #(10 * NPIX * NFRAMES * 20);
        $display("*** FAIL: TIMEOUT (got %0d outputs, %0d frame_done) ***", n_out, n_done);
        $finish;
    end

endmodule
